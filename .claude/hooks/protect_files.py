#!/usr/bin/env python3
"""PreToolUse hook for Edit/Write/MultiEdit: keep hands off files that must not be hand-edited.

- Secrets (`.env`, `.env.local`, ...): deny. The committed templates are editable.
- Lockfiles and generated/vendored trees: deny, with the command that regenerates them.
- A migration already on origin/main: ask. deploy-db has very likely run it in
  production, and an edited migration never runs again.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _common import BACKEND, FRONTEND, ROOT, emit, read_event, relative  # noqa: E402

TEMPLATES = {".env.example", ".env.docker.example"}

GENERATED: list[tuple[str, str]] = [
    (f"{BACKEND}/composer.lock", "Change dependencies with `docker compose exec -T app composer require|update <pkg>`."),
    (f"{FRONTEND}/yarn.lock", "Change dependencies with `docker compose exec -T react yarn add|upgrade <pkg>`."),
    (f"{BACKEND}/vendor/", "Vendored code; change it upstream or via composer."),
    (f"{FRONTEND}/node_modules/", "Installed packages; change them via yarn."),
    (f"{FRONTEND}/build/", "Build output of `yarn build`."),
    (f"{BACKEND}/bootstrap/cache/", "Regenerated by composer's package discovery."),
    (f"{BACKEND}/storage/", "Runtime storage, not source."),
]


def is_secret_env(name: str) -> bool:
    return name.startswith(".env") and name not in TEMPLATES


def on_origin_main(rel: str) -> bool:
    for ref in ("origin/main", "main"):
        probe = subprocess.run(["git", "cat-file", "-e", f"{ref}:{rel}"], cwd=ROOT,
                               capture_output=True, timeout=5)
        if probe.returncode == 0:
            return True
        # Ref missing entirely (fresh clone without origin/main): try the next one.
        exists = subprocess.run(["git", "rev-parse", "--verify", "--quiet", ref], cwd=ROOT,
                                capture_output=True, timeout=5)
        if exists.returncode == 0:
            return False
    return False


def decide(decision: str, reason: str) -> int:
    emit({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": decision,
        "permissionDecisionReason": reason,
    }})
    return 0


def main() -> int:
    event = read_event()
    tool_input = event.get("tool_input") or {}
    path = tool_input.get("file_path") if isinstance(tool_input, dict) else None
    if not isinstance(path, str):
        return 0
    rel = relative(path)
    if rel is None:
        return 0

    if is_secret_env(Path(rel).name):
        return decide("deny", f"{rel} holds local secrets and is gitignored. Edit the committed template "
                              "(`.env.example` / `.env.docker.example`) and tell the user what to copy.")

    for prefix, reason in GENERATED:
        if rel == prefix or rel.startswith(prefix):
            return decide("deny", f"{rel} is generated. {reason}")

    if rel.startswith(f"{BACKEND}/database/migrations/") and rel.endswith(".php"):
        try:
            shipped = on_origin_main(rel)
        except (OSError, subprocess.TimeoutExpired):
            shipped = False
        if shipped:
            return decide("ask", f"{rel} is already on main, so deploy-db has probably run it against "
                                 "production; an edited migration is never re-run. Write a new migration "
                                 "unless this is a mechanical change (e.g. Rector) with no schema effect.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
